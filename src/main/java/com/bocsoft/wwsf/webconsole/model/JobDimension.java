package com.bocsoft.wwsf.webconsole.model;

public class JobDimension {
	
	public String jobId;
	public String modelNo;
	public String dmsnName;
	public String dmsnProduct;
	public String entityName;
	
	public String getJobId() {
		return jobId;
	}
	public void setJobId(String jobId) {
		this.jobId = jobId;
	}
	public String getModelNo() {
		return modelNo;
	}
	public void setModelNo(String modelNo) {
		this.modelNo = modelNo;
	}
	public String getDmsnName() {
		return dmsnName;
	}
	public void setDmsnName(String dmsnName) {
		this.dmsnName = dmsnName;
	}
	public String getDmsnProduct() {
		return dmsnProduct;
	}
	public void setDmsnProduct(String dmsnProduct) {
		this.dmsnProduct = dmsnProduct;
	}
	public String getEntityName() {
		return entityName;
	}
	public void setEntityName(String entityName) {
		this.entityName = entityName;
	}
	
}
